// 判断一个类型在共享内存中的大小是否是「动态」的（需要递归累加）
bool NeedsDynamicExtent(const Type& t);

bool StructNeedsDynamicExtent(const Struct& s) {
  for (const auto& f : s.fields) {
    if (NeedsDynamicExtent(*f.type)) return true;
  }
  return false;
}

bool NeedsDynamicExtent(const Type& t) {
  switch (t.kind) {
    case TypeKind::STRING:
    case TypeKind::VECTOR:
      return true;
    case TypeKind::USER_DEF: {
      const auto* s = dynamic_cast<const Struct*>(&t);
      return s != nullptr && StructNeedsDynamicExtent(*s);
    }
    case TypeKind::FIXED_ARRAY: {
      const auto* a = dynamic_cast<const FixedArrayType*>(&t);
      return a != nullptr && a->element_type && NeedsDynamicExtent(*a->element_type);
    }
    default:
      return false;
  }
}

// 该类型是否需要 arena 才能构造（含容器成员，或含需要 arena 的嵌套 struct）
bool NeedsArena(const Type& t);

bool StructNeedsArena(const Struct& s) {
  for (const auto& f : s.fields) {
    if (NeedsArena(*f.type)) return true;
  }
  return false;
}

bool NeedsArena(const Type& t) {
  switch (t.kind) {
    case TypeKind::STRING:
    case TypeKind::VECTOR:
      return true;
    case TypeKind::USER_DEF: {
      const auto* s = dynamic_cast<const Struct*>(&t);
      return s != nullptr && StructNeedsArena(*s);
    }
    case TypeKind::FIXED_ARRAY: {
      const auto* a = dynamic_cast<const FixedArrayType*>(&t);
      return a != nullptr && a->element_type && NeedsArena(*a->element_type);
    }
    default:
      return false;
  }
}

