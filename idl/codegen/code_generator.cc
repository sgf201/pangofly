CodeGenerator::CodeGenerator(const std::shared_ptr<IDLDocument>& document)
    : document_(document) {}

std::string CodeGenerator::generate() {
  std::ostringstream oss;

  oss << generate_header();
  oss << "\n";
  oss << "#pragma once\n";
  oss << "\n";
  oss << generate_includes();
  oss << "\n";
  oss << "// Begin auto-generated code\n";
  oss << "\n";

  for (const auto& ns : document_->namespaces) {
    if (ns.name.empty()) {
      for (const auto& s : ns.structs) {
        oss << generate_struct(*s);
        oss << "\n";
      }
    } else {
      oss << generate_namespace_open(ns.name) << "\n";
      for (const auto& s : ns.structs) {
        std::string struct_code = generate_struct(*s);
        std::istringstream iss(struct_code);
        std::string line;
        while (std::getline(iss, line)) {
          oss << "    " << line << "\n";
        }
      }
      oss << generate_namespace_close(ns.name) << "\n";
    }

    // PANGOFLY_SHM_MESSAGE 必须在命名空间之外展开
    for (const auto& s : ns.structs) {
      std::string qname = s->qualified_name;
      if (qname.empty()) qname = s->name;
      oss << "\nPANGOFLY_SHM_MESSAGE(::" << qname << ")\n";
    }
  }

  oss << "\n// End auto-generated code\n";

  return oss.str();
}

std::string CodeGenerator::generate_header() {
  return "/*\n"
         " * Pangofly IDL Generated Header\n"
         " * DO NOT EDIT THIS FILE MANUALLY\n"
         " * Auto-generated by Pangofly IDL Compiler (IDC)\n"
         " */\n";
}

std::string CodeGenerator::generate_includes() {
  return "#include <array>\n"
         "#include <cstddef>\n"
         "#include <cstdint>\n"
         "#include <cstring>\n"
         "\n"
         "#include \"core/shm/allocator.h\"\n"
         "#include \"core/shm/arena.h\"\n";
}

std::string CodeGenerator::generate_namespace_open(const std::string& ns) {
  return "namespace " + ns + " {\n";
}

std::string CodeGenerator::generate_namespace_close(const std::string& ns) {
  (void)ns;
  return "} // namespace\n";
}

std::string CodeGenerator::generate_struct(const Struct& s) {
  std::ostringstream oss;
  std::string struct_name = s.name;
  std::string qualified_name = s.qualified_name;

  if (struct_name.find("::") != std::string::npos) {
    struct_name = struct_name.substr(struct_name.find("::") + 2);
  }

  oss << "struct " << struct_name << " {\n";
  oss << "    static const char* GetTypeName() { return \"" << qualified_name << "\"; }\n";
  oss << "\n";

  for (const auto& field : s.fields) {
    oss << "    " << generate_type_name(*field.type) << " " << field.name << ";\n";
  }

  oss << "\n";

  // 构造函数。
  //   * 含容器成员（或嵌套含容器）的结构体：只提供 explicit X(Arena&)，
  //     保证对象一出生就落在共享内存里，忘传 arena 即编译错误。
  //   * 纯 POD 结构体：额外提供默认构造，以便作为 shm::vector 的元素被
  //     resize() / 数组初始化使用。
  const bool needs_arena = StructNeedsArena(s);

  oss << "    explicit " << struct_name << "(::pangofly::shm::Arena& arena)\n";
  oss << "        : ";
  bool first = true;
  for (const auto& field : s.fields) {
    if (!first) oss << ",\n          ";
    first = false;
    oss << field.name << "(";
    if (field.type->is_primitive()) {
      oss << "0";
    } else if (field.type->is_string() || field.type->is_vector() ||
               field.type->is_user_defined()) {
      oss << "arena";
    }
    oss << ")";
  }
  if (first) oss << "/* no fields */";
  oss << " {";
  if (!needs_arena) oss << " (void)arena; ";
  oss << "}\n";
  oss << "\n";

  if (!needs_arena) {
    oss << "    " << struct_name << "() = default;\n";
    oss << "\n";
  }

  // 动态部分字节数（sizeof(*this) 之外，容器在 arena 中额外占用的部分）
  oss << "    size_t DynamicSize() const {\n";
  oss << "        size_t total = 0;\n";
  for (const auto& field : s.fields) {
    GenerateDynamicExtent(oss, field, "        ");
  }
  oss << "        return total;\n";
  oss << "    }\n";

  oss << "};\n";

  return oss.str();
}

void CodeGenerator::GenerateDynamicExtent(std::ostringstream& oss, const Field& f,
                                          const std::string& indent) {
  const Type& t = *f.type;

  if (t.is_string()) {
    oss << indent << "total += " << f.name << ".size();\n";
    return;
  }

  if (t.is_vector()) {
    const auto* vt = dynamic_cast<const VectorType*>(&t);
    if (vt == nullptr || !vt->element_type) return;
    const std::string elem = generate_type_name(*vt->element_type);
    oss << indent << "total += " << f.name << ".size() * sizeof(" << elem << ");\n";
    if (NeedsDynamicExtent(*vt->element_type)) {
      oss << indent << "for (const auto& __e : " << f.name << ") total += __e.DynamicSize();\n";
    }
    return;
  }

  if (t.is_fixed_array()) {
    const auto* at = dynamic_cast<const FixedArrayType*>(&t);
    if (at == nullptr || !at->element_type) return;
    if (NeedsDynamicExtent(*at->element_type)) {
      oss << indent << "for (const auto& __e : " << f.name << ") total += __e.DynamicSize();\n";
    }
    return;
  }

  if (t.is_user_defined()) {
    const auto* st = dynamic_cast<const Struct*>(&t);
    if (st != nullptr && StructNeedsDynamicExtent(*st)) {
      oss << indent << "total += " << f.name << ".DynamicSize();\n";
    }
    return;
  }
}

std::string CodeGenerator::generate_field(const Field& f) {
  std::ostringstream oss;
  std::string cpp_type = generate_type_name(*f.type);
  oss << cpp_type << " " << f.name << "() { return " << cpp_type << "{" << f.name << "_}; }";
  return oss.str();
}

std::string CodeGenerator::generate_getter(const Field& f) {
  std::ostringstream oss;
  std::string cpp_type = generate_type_name(*f.type);
  oss << cpp_type << " " << f.name << "() { return " << f.name << "_; }";
  return oss.str();
}

std::string CodeGenerator::generate_type_name(const Type& t) {
  switch (t.kind) {
    case TypeKind::PRIMITIVE_BOOL:    return "bool";
    case TypeKind::PRIMITIVE_INT8:    return "int8_t";
    case TypeKind::PRIMITIVE_UINT8:   return "uint8_t";
    case TypeKind::PRIMITIVE_INT16:   return "int16_t";
    case TypeKind::PRIMITIVE_UINT16:  return "uint16_t";
    case TypeKind::PRIMITIVE_INT32:   return "int32_t";
    case TypeKind::PRIMITIVE_UINT32:  return "uint32_t";
    case TypeKind::PRIMITIVE_INT64:   return "int64_t";
    case TypeKind::PRIMITIVE_UINT64:  return "uint64_t";
    case TypeKind::PRIMITIVE_FLOAT32: return "float";
    case TypeKind::PRIMITIVE_FLOAT64: return "double";
    case TypeKind::USER_DEF:          return t.name;
    case TypeKind::STRING:            return "::pangofly::shm::string";
    case TypeKind::VECTOR: {
      const auto* vt = dynamic_cast<const VectorType*>(&t);
      if (vt != nullptr && vt->element_type) {
        return "::pangofly::shm::vector<" + generate_type_name(*vt->element_type) + ">";
      }
      return "::pangofly::shm::vector<uint8_t>";
    }
    case TypeKind::FIXED_ARRAY: {
      const auto* at = dynamic_cast<const FixedArrayType*>(&t);
      if (at != nullptr && at->element_type) {
        return "std::array<" + generate_type_name(*at->element_type) + ", " +
               std::to_string(at->size) + ">";
      }
      return "std::array<uint8_t, 0>";
    }
    default:
      return "void";
  }
}

